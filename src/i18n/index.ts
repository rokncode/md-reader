const dicts = { ar, en } as const;
export type Lang = keyof typeof dicts;

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  let s: string = dicts[lang][key] ?? ar[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(formatNum(lang, v)));
  return s;
}

function formatNum(lang: Lang, v: string | number) {
  return typeof v === "number" ? new Intl.NumberFormat(lang === "ar" ? "ar" : "en").format(v) : v;
}

export function useT() {
  const lang = useSettings((s) => s.lang);
  return (key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars);
}

export function applyLang(lang: Lang) {
  const html = document.documentElement;
  html.lang = lang;
  html.dir = lang === "ar" ? "rtl" : "ltr";
  document.title = translate(lang, "appName");
}
